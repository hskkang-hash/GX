# -*- coding: utf-8 -*-
"""FWS-F1-08 — 119·산림청 신고 번호 (WO-15 §5 P-357 · 턴 AK 차선 N2).

왜 번호를 화면 상수가 아니라 이 문에 두나
-----------------------------------------
번호가 화면 코드에 박히면 「번호가 바뀌었다」는 배포를 거쳐야만 반영된다. 이 절의
계약은 「1탭」이지 「어디서 왔나」가 아니지만, **번호가 곧 안전 정보**라 서버가
내는 값과 화면이 미는 `tel:` 링크가 갈리면 그 갈림을 아무도 재지 못한다(D-212 계열).
그래서 화면은 이 문이 준 값으로만 `tel:` 을 만든다 — 화면에 번호를 다시 적지 않는다.

무엇을 하지 않나
----------------
· 인증을 요구하지 않는다. 번호 자체는 비밀이 아니고(공중전화도 119를 안다),
  긴급 상황에 관문이 막으면 그 관문이 재난의 원인이 된다.
"""
from __future__ import annotations

#: ★ 값은 명세서 원문 그대로다(annex FWS §5.1 FWS-F1-08). 지어내지 않는다.
FIRE_REPORT_NUMBER = "119"
FOREST_REPORT_NUMBER = "042-481-4119"


def emergency_contacts() -> dict:
    """1탭 신고 번호 둘. 화면은 이 값으로 `tel:` 링크를 만든다."""
    return {
        "fire_report": FIRE_REPORT_NUMBER,
        "forest_report": FOREST_REPORT_NUMBER,
    }
