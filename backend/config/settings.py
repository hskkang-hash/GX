# Check if running management command
def _is_management_command():
    """Check if we're running a Django management command."""
    try:
        argv = sys.argv
        if len(argv) < 2:
            return False
        for arg in argv:
            if 'manage.py' in arg:
                return True
        return False
    except Exception:
        return False

