# -*- coding: utf-8 -*-
"""LAW-06 — **자동 분석 고지 문구는 한 문장이다** (차선 L · 2026-09-05).

왜 이 파일이 common(L1) 에 있나
-------------------------------
고지가 닿아야 하는 자리가 **둘 이상**이다:

    로그인 뒤 첫 화면   사람이 판정 후보를 처음 보는 자리
    알림 본문 꼬리      사람이 화면 밖에서 판정을 처음 보는 자리

한 자리는 커널(`kernels/k2_notify`)이 쓰고 한 자리는 화면이 쓴다. 커널은 App 을
import 할 수 없다(계층 역전 금지 · `scripts/verify_layers.py` 금지③). 그래서 문장을
App 에 두면 **두 벌이 되고**, 두 벌이 된 고지는 한쪽만 고쳐진다 — 그리고 고지는
한쪽만 고쳐진 순간부터 「우리가 뭐라고 고지했는가」에 답이 둘인 문서가 된다.

L1 에 두면 커널도 App 도 같은 한 문장을 읽는다. **문장을 여기서만 고친다.**

★ 문안의 출처 — 지어내지 않았다
--------------------------------
이 문장은 제품 언어 사전 `docs/design/GX-COPY_v1.md` §5 「2026-09-05 턴 D 추가」에
조율자가 넣어 둔 그대로다. 사전에 없는 말을 화면에 쓰지 않는다는 규칙(UX-20)이
고지 문안에도 그대로 적용된다 — 오히려 여기가 더 엄하다: 고지는 대외 문서다.

⚠ **법률 검토 대기.** 이 문장이 AI기본법이 요구하는 고지의 **충분조건**인지는
  법률대리인이 판정한다. 이 파일이 보장하는 것은 「한 문장이 두 자리에 닿는다」이지
  「그 문장이 법을 만족한다」가 아니다. 둘은 다른 사실이다.
"""
from __future__ import annotations

#: 고지의 제목. 사전의 말 그대로.
NOTICE_TITLE: str = "자동 분석 안내"

#: 고지의 본문 한 문장. **여기가 정본이다.**
#: 화면·알림·API 응답이 전부 이 상수를 읽는다.
NOTICE_BODY: str = "이 알림은 자동 분석 결과이며, 관제요원이 최종 확인합니다."

#: 고지가 닿아야 하는 자리. **이름으로 적는다** — 적어 두지 않으면 「닿았는가」를
#: 다음 사람이 셀 수 없고, 세지 못하는 고지는 빠져도 아무도 모른다.
NOTICE_SURFACES: tuple[str, ...] = (
    "로그인 뒤 첫 화면",
    "알림 본문",
)


def notice_line() -> str:
    """알림 본문 꼬리에 붙는 한 줄. 제목과 본문을 **한 줄로** 잇는다."""
    return f"{NOTICE_TITLE}: {NOTICE_BODY}"
