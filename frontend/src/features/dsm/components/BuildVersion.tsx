/**
 * P-59 — 화면 하단 오른쪽의 **버전 한 줄.**
 *
 * 두 사람이 이것을 읽는다
 * -----------------------
 *   ① **지원 창구.** 「지금 무엇이 떠 있습니까」를 전화로 물을 때, 사용자가 읽어 줄
 *      수 있는 자리가 화면에 있어야 한다. 없으면 지원은 추측으로 시작한다.
 *   ② **우리.** 낡은 번들이 떠 있는 것을 **사람이 눈으로 본다** — 턴 D 의 사고는
 *      낡은 사본이 `exit 0` 뒤에 숨었기 때문에 하루를 갔다.
 *
 * 왜 이렇게 작고 왜 안 눌리나
 * ---------------------------
 * ★ `pointerEvents: 'none'` 이다. 이 표시는 **모든 화면 위에 뜬다** — 관제 화면의
 *   오른쪽 아래에는 단추가 있고, 정보 한 줄이 단추를 삼키면 그것은 표시가 아니라
 *   고장이다. 읽히기만 하고 아무것도 가로채지 않는다.
 * ★ 자리를 차지하지 않는다(`fixed`). 흐름에 넣으면 화면마다 아래 여백이 달라지고,
 *   긴 목록의 끝에서는 아예 안 보인다.
 *
 * ★ 「알 수 없음」이 뜨는 경우가 있다. 그것은 결함 표시가 **아니라 정직한 표시**다 —
 *   커밋을 못 읽은 빌드다(`vite.config.ts` 머리말의 ③). 지어낸 해시보다 낫다.
 */
import { VERSION_LABEL } from '../constants/build';

export default function BuildVersion() {
  return (
    <div
      style={{
        position: 'fixed',
        right: 8,
        bottom: 6,
        zIndex: 1000,
        // 읽히되 가로채지 않는다 — 아래에 있는 단추가 그대로 눌린다.
        pointerEvents: 'none',
        fontSize: 11,
        lineHeight: '14px',
        opacity: 0.45,
        // 어두운 화면(월 모드)과 밝은 화면 둘 다에서 읽히는 회색 한 칸.
        color: '#8c8c8c',
        fontVariantNumeric: 'tabular-nums',
      }}
    >
      {VERSION_LABEL}
    </div>
  );
}
